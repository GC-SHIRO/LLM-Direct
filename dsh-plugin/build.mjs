import { readFileSync, writeFileSync } from 'node:fs';
const read = (name) => readFileSync(new URL(name, import.meta.url), 'utf8');
const template = read('./client/entry.js');
const js = read('./client/workbench.js').replace('export function mountWorkbench', 'function mountWorkbench');
const css = read('./client/workbench.css');
const bundle = template.replace('/* WORKBENCH_SOURCE */', () => js).replace('/* WORKBENCH_STYLES */ null', () => JSON.stringify(css));
writeFileSync(new URL('./client.js', import.meta.url), '// Generated by build.mjs; edit client/ sources.\n' + bundle);
